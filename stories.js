/**
 * Sort stories by date descending (newest first)
 * and return the requested count (or all).
 */
export function getSortedStories(limit) {
  const sorted = [...stories].sort((a, b) => new Date(b.date) - new Date(a.date));
  return limit ? sorted.slice(0, limit) : sorted;
}

/**
 * Render story cards into a grid container.
 * @param {string}  gridSelector – CSS selector for the grid container
 * @param {number|null} limit    – max cards to render (null = all)
 */
export function renderStoryCards(gridSelector, limit = null) {
  const grid = document.querySelector(gridSelector);
  if (!grid) return;

  const items = getSortedStories(limit);
  const delayClasses = ['', 'reveal-delay-1', 'reveal-delay-2'];

  grid.innerHTML = items.map((story, i) => `
    <div class="story-card reveal ${delayClasses[i % 3]}">
      <div class="story-card-img"><img src="${story.img}" alt="${story.alt}" /></div>
      <div class="story-card-body">
        <div class="story-card-meta"><span class="date">${story.label}</span></div>
        <h3>${story.title}</h3>
        <p>${story.desc}</p>
      </div>
    </div>
  `).join('');
}
